-- Hand-written upsert from staging into the final INVOICES table.
MERGE INTO PUBLIC.INVOICES t
USING STAGE.INVOICES s
  ON t.INVOICE_ID = s.INVOICE_ID
WHEN MATCHED THEN UPDATE SET
  JOB_ID = s.JOB_ID,
  AMOUNT = s.AMOUNT,
  TAX = s.TAX,
  ISSUED_TS = s.ISSUED_TS,
  PAID_FLG = s.PAID_FLG,
  LOAD_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (INVOICE_ID, JOB_ID, AMOUNT, TAX, ISSUED_TS, PAID_FLG, LOAD_TS)
  VALUES (s.INVOICE_ID, s.JOB_ID, s.AMOUNT, s.TAX, s.ISSUED_TS, s.PAID_FLG, CURRENT_TIMESTAMP());
