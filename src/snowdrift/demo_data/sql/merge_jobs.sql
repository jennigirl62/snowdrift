-- Hand-written upsert from staging into the final JOBS table.
MERGE INTO PUBLIC.JOBS t
USING STAGE.JOBS s
  ON t.JOB_ID = s.JOB_ID
WHEN MATCHED THEN UPDATE SET
  CUSTOMER_ID = s.CUSTOMER_ID,
  SERVICE_TYPE = s.SERVICE_TYPE,
  SCHEDULED_DT = s.SCHEDULED_DT,
  STATUS = s.STATUS,
  NOTES = s.NOTES,
  LOAD_TS = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (JOB_ID, CUSTOMER_ID, SERVICE_TYPE, SCHEDULED_DT, STATUS, NOTES, LOAD_TS)
  VALUES (s.JOB_ID, s.CUSTOMER_ID, s.SERVICE_TYPE, s.SCHEDULED_DT, s.STATUS, s.NOTES, CURRENT_TIMESTAMP());
